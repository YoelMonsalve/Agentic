def foo(x, y):
    """Add two values together.

    Args:
        x: The first value.
        y: The second value.

    Returns:
        The sum of x and y.
    """
    return x + y


def bar(x, y):
    """Subtract y from x.

    Args:
        x: The initial value.
        y: The value to subtract.

    Returns:
        The difference of x and y.
    """
    return x - y
